def format_evidence(hits: list[dict]) -> str:
    lines = []
    for i, h in enumerate(hits, 1):
        lines.append(f"({i}) 정책명: {h['policy_name']} / 출처: {h['source'] or '원문'}\n{h['content']}")
    return "\n\n".join(lines)
