def level_instructions(level: Level, term_hints: list[str]) -> str:
    lo, hi = level.core_sentences
    lines = [
        f"[단계] {level.code} · {level.name}",
        f"- 핵심 블록은 {lo}~{hi}문장. 문장당 평균 {level.avg_eojeol}어절 이하, 한 문장 최대 {level.max_eojeol}어절",
        f"- 한 문장에 조건은 {level.max_conditions}개까지",
        f"- 구조: {level.structure}",
        f"- 이 단계에서 특히 잘 보여줄 내용: {level.focus}",
    ]
    if level.code in ("L1", "L2", "L3"):
        lines.append('- 횟수·주기도 풀어 쓴다 (예: "한 달에 한 번, 50만 원")')
    if level.code in ("L1", "L2", "L3", "L4", "L5"):
        lines.append('- 필요하면 "예를 들면"으로 시작하는 예시를 쓸 수 있다. 예시에 숫자를 더하지 않는다')
    if level.code in ("L1", "L2"):
        lines.append('- 서류·기관·시설·제도 이름을 쉬운 말로 바꿀 때는 원래 이름을 괄호로 함께 쓴다 '
                     '(예: "보호가 끝났다는 확인서(보호종료확인서)", "보호시설(아동복지시설)"). 대상의 범위가 넓어지지 않게 한다')
    else:
        lines.append("- [용어]에 없는 원문 용어는 그대로 써도 된다. 풀이는 앱이 따로 보여준다")
    if term_hints:
        lines.append("[용어]")
        lines.extend(term_hints)
    return "\n".join(lines)


